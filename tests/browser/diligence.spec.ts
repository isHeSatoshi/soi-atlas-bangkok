import { expect, test } from '@playwright/test'

test('four options compare on one camera and drive separate diligence results', async ({ page }) => {
  await page.goto('./?measure')
  await expect(page.getByText('Fits the modeled rules', { exact: true })).toBeVisible()
  await expect(page.locator('.concept-card')).toHaveCount(4)
  const pavilion = page.locator('.concept-card').filter({ hasText: 'Street Pavilion' })
  const lantern = page.locator('.concept-card').filter({ hasText: 'Sky Lantern' })
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await page.getByRole('combobox', { name: 'Comparison design' }).selectOption('pavilion')
  const compare = page.getByRole('region', { name: 'Same-scale concept comparison' })
  await expect(compare).toContainText('C minus A')
  await compare.getByRole('button', { name: 'View Street Pavilion in the same camera' }).click()
  await expect(pavilion).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.model-caption')).toContainText('Street Pavilion')
  await lantern.click()
  await expect(compare).toContainText('D minus A')
  await expect(page.locator('.model-caption')).toContainText('Sky Lantern')
  if (process.env.CAPTURE_EXTENDED === '1') {
    await page.setViewportSize({ width: 1366, height: 1000 })
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
    await page.screenshot({ path: 'docs/evidence/06-four-options.png' })
  }
  await page.getByRole('link', { name: 'Due diligence', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Due diligence' })
  const row = (title: string) => panel.locator('details').filter({ has: page.getByText(title, { exact: true }) })
  await row('Parking').locator('summary').click()
  await row('Parking').getByLabel('Project condo units').fill('12')
  await row('Parking').getByLabel('Largest unit area (m²)').fill('60')
  await expect(row('Parking')).toContainText('12 provisional bays')
  await row('Parking').getByRole('button', { name: 'Test surface parking' }).click()
  await expect(row('Parking')).toContainText(/in the tested layout/)
  await row('Fire access').locator('summary').click()
  await row('Fire access').getByRole('button', { name: 'Test fire approach' }).click()
  await expect(row('Fire access').locator('.screen-result')).toContainText('3.5 m straight approach')
  await expect(row('Egress')).toContainText('Fire stair flagged')
  await row('Environmental impact assessment').locator('summary').click()
  await row('Environmental impact assessment').getByLabel('Units across the full project').fill('80')
  await expect(row('Environmental impact assessment')).toContainText('Size trigger flagged')
  await expect(row('Structure')).toContainText('Engineer review')
  await expect(row('Permits')).toContainText('Authority review')
  if (process.env.CAPTURE_EXTENDED === '1') await panel.screenshot({ path: 'docs/evidence/07-due-diligence.png' })
})

test('an entered reservation changes the envelope and a known grade mismatch withholds fits', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./')
  await expect(page.getByText('Fits the modeled rules', { exact: true })).toBeVisible()
  const panel = page.getByRole('region', { name: 'Due diligence' })
  const reservation = panel.locator('details').filter({ hasText: /Utilities, easements & overlays/ })
  await reservation.locator('summary').click()
  await reservation.getByLabel('Reservation type').selectOption('Utility')
  await reservation.getByLabel('Rear no-build depth (m)').fill('6')
  await expect(reservation).toContainText('m² reserved on the map')
  await expect(page.getByText('No-build strip', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /User-entered no-build strip/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  const assumptions = panel.locator('details').filter({ hasText: /Site model assumptions/ })
  await assumptions.locator('summary').click()
  await assumptions.getByLabel('Known mismatch').selectOption('grade')
  await expect(page.getByText(/known road or site grade differs/)).toBeVisible()
  await expect(page.getByText('Fits the modeled rules', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reset example' }).click()
  await expect(page.getByText('Fits the modeled rules', { exact: true })).toBeVisible()
  await expect(page.getByText('No-build strip', { exact: true })).toHaveCount(0)
})
